        cat = yield C("search_training_catalog", {"query": q, "product": prod, "top_k": 6}, "Find training that matches the goal and meeting purpose.")
        if not cat.result["ok"] or not cat.result["data"]["courses"]:
            return Finish("No matching training in the catalog; no recommendation saved.")
