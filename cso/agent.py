"""Bounded agent loop plus the scripted decider.

One onboarding agent. The loop asks a *decider* for the next structured tool call, executes it through the
validated tool layer, and stops on Finish, an error, or the configured step limit.

Two deciders share this loop and the same tools/state:
  - ScriptedDecider: deterministic rules. Not an LLM. Labelled "Scripted demo".
  - LiveDecider (llm.py): a model chooses tools. Labelled "Live AI".
"""
from __future__ import annotations

import json
from dataclasses import dataclass, field
from datetime import timedelta

from .db import DB, to_iso
from .models import MILESTONE_QUERY, PRODUCT_LABEL
from .tools import TOOLS, ToolContext, execute_tool

OBJECTIVE = ("Help eligible customers reach their planned onboarding milestones using relevant guidance, "
             "while respecting customer preferences and escalating unresolved problems to the appropriate team.")


@dataclass
class Call:
    tool: str
    args: dict
    rationale: str = ""


@dataclass
class Finish:
    summary: str
    prevented: list[str] = field(default_factory=list)


@dataclass
class Obs:
    tool: str
    args: dict
    result: dict


class LLMError(Exception):
    pass


# ------------------------------------------------------------ message text ---
def _first(name: str) -> str:
    return (name or "there").split()[0]


def _quote(excerpt: str, n: int = 4) -> str:
    lines = [l.strip() for l in excerpt.splitlines() if l.strip()][:n]
    return "\n".join(("  " + l) if l[:2].rstrip(".").isdigit() else "  - " + l for l in lines)


def _sources(hits: list[dict]) -> str:
    seen, out = set(), []
    for h in hits:
        k = (h["doc_id"], h["section"])
        if k not in seen:
            seen.add(k); out.append(f"{h['doc_id']} - {h['title']} > {h['section']}")
    return "Sources: " + "; ".join(out)


def _doc_ids(hits: list[dict]) -> list[str]:
    return list(dict.fromkeys(h["doc_id"] for h in hits))


class ScriptedDecider:
    """Rule-based decisions. These are not generated by a language model."""
    label = "Scripted demo (rule-based, no LLM)"

    def __init__(self, db: DB, account_id: str, journey_id: str, trigger: dict):
        self.db, self.aid, self.jid, self.trigger = db, account_id, journey_id, trigger
        self.gen = self._flow()
        self.started = False

    def decide(self, obs: list[Obs]):
        try:
            if not self.started:
                self.started = True
                return next(self.gen)
            return self.gen.send(obs[-1])
        except StopIteration as e:
            return e.value if isinstance(e.value, Finish) else Finish(str(e.value or "Done."))

    def observe(self, call, result):
        pass

    # ---- flows ----------------------------------------------------------------
    def _flow(self):
        db, aid, jid = self.db, self.aid, self.jid
        j = db.one("SELECT * FROM journeys WHERE id=?", (jid,))
        prod = j["product"]
        C = lambda tool, args, why: Call(tool, {"account_id": aid, **args}, why)
        cx = yield C("get_customer_context", {"journey_id": jid}, "Gather goal, rollout plan, contact preferences and current outreach eligibility.")
        pr = yield C("get_setup_progress", {"product": prod}, "Read fresh milestone progress before deciding anything.")
        hist = yield C("get_interaction_history", {"journey_id": jid}, "Check guidance already sent and steps the customer already tried.")
        cs = yield C("check_support_cases", {"product": prod}, "Look for open cases that could conflict with outreach.")
        for name, o in (("context", cx), ("progress", pr), ("history", hist), ("support cases", cs)):
            if not o.result["ok"]:
                return Finish(f"Stopped: could not read {name} ({o.result['error']['code']}). No action taken.")
        self.cx, self.pr, self.hist, self.cs = cx.result["data"], pr.result["data"], hist.result["data"], cs.result["data"]
        self.prod, self.j = prod, j
        t = self.trigger["type"]
        if t == "customer_reply":
            return (yield from self._reply())
        if t == "progress_check":
            return (yield from self._progress_check())
        return (yield from self._proactive())

    def _call(self, tool, **args):
        return Call(tool, {"account_id": self.aid, **args}, "")

    def _state(self):
        return self.db.one("SELECT state FROM journeys WHERE id=?", (self.jid,))["state"]

    def _complete(self, reason):
        r = yield Call("update_journey_status", {"account_id": self.aid, "journey_id": self.jid, "new_state": "completed", "reason": reason},
                       "Fresh progress shows every milestone done, so close the journey and cancel reminders.")
        return r

    def _proactive(self):
        cx, pr, prod = self.cx, self.pr, self.prod
        label = PRODUCT_LABEL[prod]
        state = self._state()
        if state in ("completed", "opted_out"):
            return Finish(f"{label} journey is already {state.replace('_', ' ')}. Nothing to do.")
        if pr["complete"]:
            r = yield from self._complete("All milestones complete per fresh progress check")
            return Finish(f"Setup is complete; {r.result['data']['detail'] if r.result['ok'] else 'could not close journey: ' + r.result['error']['message']}.")
        blockers = {c["code"]: c["message"] for c in cx["eligibility"]["checks"] if not c["passed"]}
        if "opt_out" in blockers:
            return Finish("No outreach: customer opted out.", ["opt_out"])
        if "missing_data" in blockers or "stale_data" in blockers:
            code = "missing_data" if "missing_data" in blockers else "stale_data"
            return Finish(f"No outreach: {blockers[code]}. Flagged for review instead of guessing.", [code])
        if "rollout_started" in blockers:
            if state in ("monitoring", "guidance_sent", "waiting_for_customer"):
                r = yield Call("pause_journey", {"account_id": self.aid, "journey_id": self.jid, "reason": "until_rollout"},
                               "Rollout has not started, so outreach must wait. Pause until the planned date.")
                return Finish(f"{blockers['rollout_started']}. " + ("Journey paused until rollout." if r.result["ok"] else f"Pause failed: {r.result['error']['message']}"), ["rollout_started"])
            return Finish(f"{blockers['rollout_started']}. Already paused; no outreach.", ["rollout_started"])
        if "no_blocking_case" in blockers:
            return Finish(f"Holding: {blockers['no_blocking_case']}. Reminders would conflict with the open case.", ["no_blocking_case"])
        for code in ("stalled", "frequency", "unanswered_cap"):
            if code in blockers:
                return Finish(f"No outreach: {blockers[code]}.", [code])
        nm = pr["next_milestone"]
        attempted = self.hist["attempted_doc_ids"]
        s = yield Call("search_documentation", {"account_id": self.aid, "query": MILESTONE_QUERY[(prod, nm["key"])], "product": prod,
                                                "top_k": 2, "exclude_doc_ids": attempted}, f"Find guidance for the next milestone: {nm['label']}.")
        if not s.result["ok"] or not s.result["data"]["supported"]:
            return Finish("No documentation supports this milestone; no message sent. Flagged for content review.", ["no_docs"])
        hits = s.result["data"]["hits"]
        acc, contact = cx["account"], cx["contact"]
        last = pr["last_progress_at"]
        body = (f"Hi {_first(contact['name'])},\n\nSetup for {label} at {acc['name']} looks paused"
                f"{' since ' + last[:10] if last else ''}. Your goal is: \"{acc['goal']}\"\n\n"
                f"The next step is \"{nm['label']}\":\n{_quote(hits[0]['excerpt'])}\n\n{_sources(hits[:1])}\n\n"
                "If something is blocking you, reply here and I'll help.")
        snd = yield Call("send_guidance", {"account_id": self.aid, "journey_id": self.jid, "contact_id": contact["id"], "channel": contact["preferred_channel"],
                                           "kind": "proactive", "subject": f"Next step for your {label} setup", "body": body, "doc_ids": _doc_ids(hits[:1])},
                         "Customer is eligible and stalled; send the next-step guidance with its source.")
        if not snd.result["ok"]:
            return Finish(f"Message not sent: {snd.result['error']['message']}", ["send_blocked"])
        yield Call("update_journey_status", {"account_id": self.aid, "journey_id": self.jid, "new_state": "waiting_for_customer",
                                             "reason": "Guidance sent; waiting for reply"}, "Record that we are waiting on the customer.")
        return Finish(f"Sent {nm['label']} guidance via {contact['preferred_channel']}; next reminder {snd.result['data']['next_reminder_at']}.")

    def _progress_check(self):
        pr, prod, cx = self.pr, self.prod, self.cx
        label = PRODUCT_LABEL[prod]
        if pr["complete"]:
            r = yield from self._complete("Fresh check after human resolution shows setup complete")
            return Finish("Fresh progress check: all milestones complete. " + (r.result["data"]["detail"] if r.result["ok"] else r.result["error"]["message"]))
        rs = yield Call("resume_journey", {"account_id": self.aid, "journey_id": self.jid, "reason": "Support task resolved; fresh progress check done"},
                        "A person resolved the case. Do not assume success: resume monitoring based on fresh progress.")
        if not rs.result["ok"]:
            return Finish(f"Could not resume journey: {rs.result['error']['message']}")
        nm = pr["next_milestone"]
        s = yield Call("search_documentation", {"account_id": self.aid, "query": MILESTONE_QUERY[(prod, nm["key"])], "product": prod, "top_k": 1,
                                                "exclude_doc_ids": self.hist["attempted_doc_ids"]}, f"Find guidance for the next milestone: {nm['label']}.")
        hits = s.result["data"]["hits"] if s.result["ok"] and s.result["data"]["supported"] else []
        note = self.trigger.get("note", "")
        body = (f"Hi {_first(cx['contact']['name'])},\n\nUpdate from our team on your {label} request: {note}\n\n"
                f"We checked your setup just now. Done so far: {pr['done_count']} of {pr['total']} milestones. Next up is \"{nm['label']}\"."
                + (f"\n{_quote(hits[0]['excerpt'], 3)}\n\n{_sources(hits)}" if hits else "")
                + "\n\nThe support request is resolved; your onboarding continues from here.")
        snd = yield Call("send_guidance", {"account_id": self.aid, "journey_id": self.jid, "contact_id": cx["contact"]["id"], "channel": cx["contact"]["preferred_channel"],
                                           "kind": "status_update", "subject": f"Update on your {label} request", "body": body, "doc_ids": _doc_ids(hits)},
                         "Tell the customer the case is resolved and what comes next.")
        if snd.result["ok"]:
            yield Call("update_journey_status", {"account_id": self.aid, "journey_id": self.jid, "new_state": "waiting_for_customer", "reason": "Status update sent"}, "Wait for the customer to continue.")
        return Finish(f"Support task resolved, onboarding not complete: next milestone is '{nm['label']}'. Journey resumed"
                      + ("; customer updated." if snd.result["ok"] else f"; customer not messaged ({snd.result['error']['message']})."))

    def _reply(self):
        tr, cx, pr, hist, cs, prod = self.trigger, self.cx, self.pr, self.hist, self.cs, self.prod
        intent, ch, text = tr["intent"], tr["channel"], tr["text"]
        label = PRODUCT_LABEL[prod]
        contact = cx["contact"]
        if not contact:
            return Finish("No administrator contact on file; cannot reply. Flagged for review.", ["missing_data"])

        def reply(body, docs=(), why="Reply to the customer's message."):
            return Call("send_guidance", {"account_id": self.aid, "journey_id": self.jid, "contact_id": contact["id"], "channel": ch, "kind": "reply",
                                          "subject": f"Re: your {label} setup", "body": body, "doc_ids": list(docs)}, why)

        def wait():
            return Call("update_journey_status", {"account_id": self.aid, "journey_id": self.jid, "new_state": "waiting_for_customer",
                                                  "reason": "Replied; waiting for customer"}, "Record that we are waiting on the customer.")

        hi = f"Hi {_first(contact['name'])},\n\n"
        if intent == "policy_override":
            r = yield reply(hi + "I can't change my instructions, make exceptions to account policies, or act on other accounts, and I can't change billing, "
                            "plans or permissions. I can help with your onboarding steps. Tell me where you're stuck.", why="Decline the request; policies are enforced in code.")
            return Finish("Rejected a message that tried to override policies; no tools beyond a safe reply were used.")
        if intent == "opt_out":
            r = yield Call("send_guidance", {"account_id": self.aid, "journey_id": self.jid, "contact_id": contact["id"], "channel": ch, "kind": "confirmation",
                                             "body": hi + "Understood. I've stopped all onboarding messages for your account. You can contact support any time.",
                                             "subject": "Messages stopped"}, "Acknowledge the opt-out once, before stopping.")
            o = yield Call("update_journey_status", {"account_id": self.aid, "journey_id": self.jid, "new_state": "opted_out", "reason": "Customer asked to stop messages"},
                           "Honour the opt-out for every journey on the account.")
            return Finish("Customer opted out. " + (o.result["data"]["detail"] if o.result["ok"] else "Opt-out update failed: " + o.result["error"]["message"]))
        if intent == "setup_complete":
            if pr["complete"]:
                r = yield reply(hi + f"Great news: we can see all {label} milestones are complete ({pr['done_count']} of {pr['total']}). I've stopped setup reminders. Congratulations!",
                                why="Fresh progress confirms the claim, so confirm it.")
                c = yield from self._complete("Customer reported completion; verified by fresh product events")
                return Finish("Verified completion from product events. " + (c.result["data"]["detail"] if c.result["ok"] else c.result["error"]["message"]))
            left = ", ".join(m["label"] for m in pr["milestones"] if not m["done"])
            r = yield reply(hi + f"Thanks! I checked your {label} setup and I don't see these yet: {left}. Data can lag a little, so reply if you believe they're done.",
                            why="Customer claim not supported by product data; do not mark complete.")
            yield wait()
            return Finish(f"Customer said setup is complete but product events disagree (remaining: {left}). Not marked complete.")
        if intent == "rollout_later":
            resume = (self.db.now() + timedelta(days=30)).date().isoformat()
            p = yield Call("pause_journey", {"account_id": self.aid, "journey_id": self.jid, "reason": "customer_request", "resume_on": resume},
                           "Customer says rollout starts later; pause outreach until then.")
            if not p.result["ok"]:
                return Finish(f"Could not pause journey: {p.result['error']['message']}. No promise made to the customer.")
            yield reply(hi + f"Thanks for letting me know. I'll hold off on {label} messages and check back around {resume}. Reply any time if you want help sooner.")
            return Finish(f"Customer rollout is later; journey paused until {resume}.")
        if intent == "not_started":
            nm = pr["next_milestone"]
            s = yield Call("search_documentation", {"account_id": self.aid, "query": MILESTONE_QUERY[(prod, nm["key"])], "product": prod, "top_k": 2,
                                                    "exclude_doc_ids": hist["attempted_doc_ids"]}, "Find the first step they need.")
            hits = s.result["data"]["hits"] if s.result["ok"] and s.result["data"]["supported"] else []
            if not hits:
                yield reply(hi + "I couldn't find a guide that covers that step, so I won't guess. I can connect you with a specialist if you'd like.")
                return Finish("No supported docs; offered handoff.")
            r = yield reply(hi + f"No problem. Here is where to start with {label}: \"{nm['label']}\".\n{_quote(hits[0]['excerpt'])}\n\n{_sources(hits[:1])}",
                            _doc_ids(hits[:1]))
            if r.result["ok"]:
                yield wait()
            return Finish("Sent getting-started guidance." if r.result["ok"] else f"Message not sent: {r.result['error']['message']}")
        if intent in ("tried_steps",) or (intent == "issue_directory" and hist["troubleshooting_replies"] >= self.db.get_settings().max_troubleshooting_replies):
            if not self.db.get_settings().handoff_on_tried_steps and intent == "tried_steps":
                pass
            else:
                return (yield from self._escalate(reply, wait, hi, text))
        if intent == "issue_directory":
            if cs["blocking"]:
                t = cs["open_tasks"][0]["id"] if cs["open_tasks"] else cs["open_cases"][0]["id"]
                yield reply(hi + f"We already have an open request for this ({t}) and our team is working on it, so I won't send more steps that could conflict. I'll update you here when it moves.")
                return Finish(f"Open support request {t} exists; sent status only, no new guidance or handoff.")
            q = "directory integration troubleshooting authentication error connection timed out sync fails " + text
            s = yield Call("search_documentation", {"account_id": self.aid, "query": q, "product": prod, "top_k": 3,
                                                    "exclude_doc_ids": hist["guidance_doc_ids"]}, "Retrieve troubleshooting docs not already sent.")
            return (yield from self._answer_from_docs(s, reply, wait, hi))
        s = yield Call("search_documentation", {"account_id": self.aid, "query": text, "product": prod, "top_k": 2,
                                                "exclude_doc_ids": hist["attempted_doc_ids"]}, "Look for documentation that answers the question.")
        return (yield from self._answer_from_docs(s, reply, wait, hi))

    def _answer_from_docs(self, s, reply, wait, hi):
        ok = s.result["ok"] and s.result["data"]["supported"]
        if not ok:
            offer = " I can connect you with a specialist if you'd like - just reply \"yes\"." if self.db.get_settings().offer_handoff_when_docs_unsupported else ""
            yield reply(hi + "I couldn't find documentation that covers that, and I don't want to guess." + offer, why="Docs do not support an answer; explain the limit instead of improvising.")
            return Finish("Documentation did not support the question; explained the limit and offered a handoff.")
        hits = s.result["data"]["hits"][:3]
        steps = "\n\n".join(f"{h['section']}:\n{_quote(h['excerpt'], 3)}" for h in hits[:2])
        r = yield reply(hi + f"Here is what our documentation says:\n\n{steps}\n\n{_sources(hits[:2])}\n\nIf you've already tried these, tell me and I'll bring in our support team.",
                        _doc_ids(hits[:2]))
        if r.result["ok"]:
            yield wait()
            return Finish(f"Sent guidance grounded in {', '.join(_doc_ids(hits[:2]))}.")
        return Finish(f"Message not sent: {r.result['error']['message']}")

    def _escalate(self, reply, wait, hi, text):
        pr, hist, prod, cx = self.pr, self.hist, self.prod, self.cx
        label = PRODUCT_LABEL[prod]
        attempted = hist["attempted_doc_ids"]
        category = "integration" if ("directory" in text.lower() or any(d in ("DOC-104", "DOC-105") for d in attempted + hist["guidance_doc_ids"])) else "configuration"
        summary = (f"Customer goal: {cx['account']['goal']} Customer reports the documented steps did not work ({', '.join(attempted) or 'no docs recorded'}). "
                   f"Progress: {pr['done_count']} of {pr['total']} {label} milestones. Latest message: \"{text[:160]}\"")
        h = yield Call("create_handoff", {"account_id": self.aid, "journey_id": self.jid, "issue": f"{label}: " + ("directory integration still failing after documented steps" if category == "integration" else "setup issue after documented steps"),
                                          "category": category, "priority": "medium", "summary": summary, "attempted_doc_ids": attempted},
                       "Customer already tried the documented steps; escalate with context instead of repeating guidance.")
        if not h.result["ok"]:
            r = yield reply(hi + "I tried to hand this to our technical team, but the request did not go through, so nothing has been created yet. "
                            "Please reply \"talk to a person\" and I'll retry, or contact support directly. I won't resend the same steps.", why="Handoff failed; say so plainly.")
            if r.result["ok"]:
                yield wait()
            return Finish(f"Handoff FAILED ({h.result['error']['code']}); customer told nothing was created.")
        d = h.result["data"]
        if d["existing"]:
            yield reply(hi + f"Our {d['team']} team already has this open as {d['task_id']}, so I haven't created a duplicate. They have your earlier steps and I'll share updates here.", why="An open task already exists.")
            return Finish(f"Open task {d['task_id']} already exists; duplicate escalation prevented.")
        p = yield Call("pause_journey", {"account_id": self.aid, "journey_id": self.jid, "reason": "awaiting_human"}, "Pause reminders so we don't conflict with the human team.")
        paused = " I've paused setup reminders until they respond." if p.result["ok"] else ""
        yield reply(hi + f"Thanks for confirming you already tried those steps. I've created {d['task_id']} for our {d['team']} team with your goal, what we sent and what you tried, so you won't need to repeat yourself.{paused}",
                    why="Handoff succeeded; tell the customer exactly what happened.")
        return Finish(f"Created {d['task_id']} for {d['team']}; " + ("reminders paused." if p.result["ok"] else "pause failed."))


# --------------------------------------------------------------- the loop ---
def idem_key(trigger: dict, journey_id: str, call: Call) -> str | None:
    spec = TOOLS.get(call.tool)
    if not spec or not spec.mutating:
        return None
    a = call.args
    disc = a.get("kind") or a.get("new_state") or a.get("reason") or ""
    return f"{trigger['ref']}|{journey_id}|{call.tool}|{disc}"


def run_agent(db: DB, account_id: str, journey_id: str, trigger: dict, mode: str = "scripted", llm_settings: dict | None = None,
              max_steps: int | None = None) -> dict:
    st = db.get_settings()
    max_steps = max_steps or st.max_agent_steps
    run_id = db.next_id("RUN")
    model = None
    if mode == "live":
        from .llm import LiveDecider
        model = (llm_settings or {}).get("model")
        decider = LiveDecider(db, account_id, journey_id, trigger, **(llm_settings or {}))
    else:
        decider = ScriptedDecider(db, account_id, journey_id, trigger)
    db.insert("agent_runs", id=run_id, account_id=account_id, journey_id=journey_id, mode=mode, model=model, trigger=trigger["type"],
              trigger_ref=trigger["ref"], started_at=to_iso(db.now()))
    ctx = ToolContext(db, run_id, account_id)
    obs: list[Obs] = []
    outcome, summary, error, steps, prevented = "step_limit", "Stopped at the step limit before finishing.", None, 0, []
    while True:
        try:
            d = decider.decide(obs)
        except LLMError as e:
            outcome, error, summary = "error", str(e), "Live AI call failed; no further actions were taken."
            break
        if isinstance(d, Finish):
            outcome, summary, prevented = "completed", d.summary, d.prevented
            break
        if steps >= max_steps:
            break  # execution limit reached: stop instead of acting further
        res = execute_tool(ctx, d.tool, d.args, d.rationale, idem_key(trigger, journey_id, d))
        steps += 1
        obs.append(Obs(d.tool, d.args, res))
        if hasattr(decider, "observe"):
            decider.observe(d, res)
    if prevented and trigger["type"] != "customer_reply":
        db.guard("outreach_prevented", account_id, journey_id, ",".join(prevented))
    db.x("UPDATE agent_runs SET finished_at=?, steps=?, outcome=?, summary=?, error=? WHERE id=?",
         (to_iso(db.now()), steps, outcome, summary, error, run_id))
    return {"run_id": run_id, "outcome": outcome, "summary": summary, "error": error, "steps": steps}
