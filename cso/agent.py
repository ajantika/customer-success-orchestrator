# ------------------------------------------------------------ message text ---
def _first(name: str) -> str:
    return (name or "there").split()[0]


def _quote(excerpt: str, n: int = 4) -> str:
    lines = [humanize(l.strip()) for l in excerpt.splitlines() if l.strip()][:n]
    return "\n".join(("  " + l) if l[:2].rstrip(".").isdigit() else "  - " + l for l in lines)


def _doc_ids(hits: list[dict]) -> list[str]:
    """Documents to cite: the retrieved ones plus any document their excerpts point to (valid cross-references)."""
    ids = list(dict.fromkeys(h["doc_id"] for h in hits))
    known = get_retriever().doc_ids()
    for h in hits:
        for d in re.findall(r"DOC-\d{3}", h["excerpt"]):
            if d in known and d not in ids:
                ids.append(d)
    return ids


def _sources(hits: list[dict]) -> str:
    """Plain source line for a customer message. Document IDs stay out of the text and live in the source details."""
    titles = {c.doc_id: c.title for c in get_retriever().chunks}
    seen, out = set(), []
    for h in hits:
        k = (h["doc_id"], h["section"])
        if k not in seen:
            seen.add(k); out.append(f"{h['title']} — {h['section']}")
    for d in _doc_ids(hits):
        if d not in {h["doc_id"] for h in hits}:
            out.append(titles[d])
    return ("Source used: " if len(out) == 1 else "Sources used: ") + "; ".join(out)


class ScriptedDecider:
    """Rule-based decisions. These are not generated by a language model."""
    label = "Demo mode (prepared scenarios and rules, no AI model)"

    def __init__(self, db: DB, account_id: str, journey_id: str, trigger: dict):
        self.db, self.aid, self.jid, self.trigger = db, account_id, journey_id, trigger
        self.gen = self._flow()
        self.started = False

    def decide(self, obs: list[Obs]):
        try:
            if not self.started:
                self.started = True
                return next(self.gen)
            return self.gen.send(obs[-1])
        except StopIteration as e:
            return e.value if isinstance(e.value, Finish) else Finish(str(e.value or "Done."))

    def observe(self, call, result):
        pass

    # ---- flows ----------------------------------------------------------------
    def _flow(self):
        db, aid, jid = self.db, self.aid, self.jid
        if self.trigger["type"] == "meeting_prep":
            return (yield from self._meeting_flow())
        j = db.one("SELECT * FROM journeys WHERE id=?", (jid,))
        prod = j["product"]
        C = lambda tool, args, why: Call(tool, {"account_id": aid, **args}, why)
        cx = yield C("get_customer_context", {"journey_id": jid}, "Gather goal, rollout plan, contact preferences and current outreach eligibility.")
        pr = yield C("get_setup_progress", {"product": prod}, "Read fresh milestone progress before deciding anything.")
        hist = yield C("get_interaction_history", {"journey_id": jid}, "Check guidance already sent and steps the customer already tried.")
        cs = yield C("check_support_cases", {"product": prod}, "Look for open cases that could conflict with outreach.")
        for name, o in (("context", cx), ("progress", pr), ("history", hist), ("support cases", cs)):
            if not o.result["ok"]:
                return Finish(f"Stopped: could not read {name} ({o.result['error']['code']}). No action taken.")
        self.cx, self.pr, self.hist, self.cs = cx.result["data"], pr.result["data"], hist.result["data"], cs.result["data"]
        self.prod, self.j = prod, j
        t = self.trigger["type"]
        if t == "customer_reply":
            return (yield from self._reply())
        if t == "progress_check":
            return (yield from self._progress_check())
        return (yield from self._proactive())

    # ---- Meeting preparation ----------------------------------------
    def _save(self, mid, action, title, why, talking, brief, refs, **extra):
        args = {"account_id": self.aid, "meeting_id": mid, "action_type": action, "title": title, "why_now": why, "talking_point": talking,
                "brief": brief, "evidence_refs": refs, **extra}
        return Call("save_recommendation", args, "Save the recommendation for human review. Nothing is sent to the customer.")

